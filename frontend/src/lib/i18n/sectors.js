export function translateSector(sec, lang = 'en') {
  if (!sec) return '';
  if (lang !== 'hi') return sec;
  return SECTOR_MAP[sec] || sec;
}

export function translateState(st, lang = 'en') {
  if (!st) return '';
  if (lang !== 'hi') return st;
  return STATE_MAP[st] || st;
}

export function translateStatus(status, lang = 'en') {
  if (!status) return '';
  if (lang !== 'hi') return status;
  return STATUS_MAP[status] || status;
}

export function translateAgency(agency, lang = 'en') {
  if (!agency) return '';
  if (lang !== 'hi') return agency;
  return AGENCY_MAP[agency] || agency;
}

export function translateProjectName(name, lang = 'en') {
  if (!name) return '';
  if (lang !== 'hi') return name;
  if (FEATURED_PROJECT_NAMES[name]) return FEATURED_PROJECT_NAMES[name];

  let res = String(name);
  for (const [from, to] of KEYWORD_REPLACEMENTS) {
    if (res.includes(from)) {
      res = res.replaceAll(from, to);
    }
  }
  return res;
}
